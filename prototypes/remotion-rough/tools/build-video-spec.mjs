import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const viewerRoot = path.resolve(projectRoot, '..', 'storyboard-viewer');
const sourcePath = path.join(viewerRoot, 'storyboard-data.js');
const outputPath = path.join(projectRoot, 'src', 'video-spec.generated.js');

const source = fs.readFileSync(sourcePath, 'utf8');
const sandbox = {window: {}};
vm.runInNewContext(source, sandbox, {filename: sourcePath});
const storyboard = sandbox.window.STORYBOARD_DATA;

if (!storyboard?.frames?.length) {
  throw new Error('storyboard-data.js did not expose window.STORYBOARD_DATA.frames');
}

const fps = 30;
const charactersPerSecond = 12;
const preRollFrames = 12;
const ordinaryHoldFrames = 36;

// Current rough-direction choices. The timing constants above are owner-accepted;
// these longer per-beat holds remain adjustable after watching the rough.
const holdFramesById = {
  F03: 48,
  F04: 42,
  F05: 48,
  F06: 42,
  F15: 54,
  F17: 48,
  F18: 48,
  F19: 66,
};

let cursor = 0;
const frames = storyboard.frames.map((frame) => {
  const dialogue = typeof frame.dialogue === 'string' ? frame.dialogue : '';
  const hasDialogue = dialogue.trim().length > 0;
  const charCount = Array.from(dialogue).length;
  const revealFrames = hasDialogue
    ? Math.ceil((charCount / charactersPerSecond) * fps)
    : 0;
  const preRoll = hasDialogue ? preRollFrames : 0;
  const holdFrames = holdFramesById[frame.id] ?? ordinaryHoldFrames;
  const durationFrames = preRoll + revealFrames + holdFrames;
  const startFrame = cursor;
  cursor += durationFrames;

  return {
    id: frame.id,
    startFrame,
    durationFrames,
    preRollFrames: preRoll,
    revealFrames,
    holdFrames,
    dialogue,
    speakerPanel: frame.speakerPanel,
    layout: frame.layout,
    panels: frame.panels.map((panel) => ({
      subject: panel.subject,
      asset: panel.asset,
      position: panel.position,
      align: panel.align,
      zoom: panel.zoom,
    })),
  };
});

const spec = {
  schemaVersion: 'rough-video-spec-0.1',
  project: {
    id: 'telegram-unblock-rough-v1',
    title: storyboard.title,
    width: 1920,
    height: 1080,
    fps,
    totalDurationFrames: cursor,
  },
  timing: {
    mode: 'typed-dialogue',
    charactersPerSecond,
    preRollFrames,
    ordinaryHoldFrames,
  },
  theme: {
    backgroundColor: '#02090b',
    panelGutterPx: 48,
    dialogueBarHeightPx: 300,
    dialogueBarColor: '#030607',
    dialogueBarBorderColor: '#536064',
    textColor: '#f6f4ed',
    fontFamily: 'Arial, Helvetica, sans-serif',
  },
  frames,
};

const moduleText = `// Generated by tools/build-video-spec.mjs. Do not edit by hand.\nexport default ${JSON.stringify(spec, null, 2)};\n`;
fs.writeFileSync(outputPath, moduleText);
console.log(`Built ${path.relative(projectRoot, outputPath)}: ${frames.length} frames, ${cursor} total frames, ${(cursor / fps).toFixed(2)} seconds`);
